"""Scoped cleanup and image identity helpers for Harbor Docker trials."""
from __future__ import annotations

import json
import re
import subprocess
import time
from pathlib import Path
from typing import Any


_TRIAL_NAME = re.compile(r"^[a-z0-9][a-z0-9_.-]*__harbor-[0-9a-f]{12}$")
_RESOURCE_COMMANDS = (
    ("containers", ("ps", "-aq"), ("rm", "-f")),
    ("networks", ("network", "ls", "-q"), ("network", "rm")),
    ("volumes", ("volume", "ls", "-q"), ("volume", "rm", "-f")),
)


def _docker(args: list[str], *, timeout: int = 30) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["docker", *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=timeout,
        check=False,
    )


def compose_project_name(trial_name: str) -> str:
    """Return the exact project name generated by Harbor for an Eval trial."""
    if not _TRIAL_NAME.fullmatch(trial_name):
        raise ValueError(f"Refusing to clean an unscoped Harbor trial name: {trial_name}")
    return trial_name + "__env"


def _project_resources(project_name: str) -> tuple[dict[str, list[str]], list[str]]:
    resources: dict[str, list[str]] = {}
    errors: list[str] = []
    label = f"com.docker.compose.project={project_name}"
    for kind, list_args, _ in _RESOURCE_COMMANDS:
        try:
            result = _docker([*list_args, "--filter", f"label={label}"])
        except (OSError, subprocess.TimeoutExpired) as error:
            errors.append(f"{kind}: {error}")
            resources[kind] = []
            continue
        if result.returncode:
            errors.append(f"{kind}: {result.stderr.strip() or result.stdout.strip() or 'docker query failed'}")
            resources[kind] = []
        else:
            resources[kind] = [line.strip() for line in result.stdout.splitlines() if line.strip()]
    return resources, errors


def cleanup_trial_environment(trial_name: str, *, attempts: int = 3) -> dict[str, Any]:
    """Remove only runtime resources for one Eval-owned Harbor Compose project.

    Images are intentionally excluded: official task images are immutable inputs and
    remain in Docker's cache for subsequent trials.
    """
    project_name = compose_project_name(trial_name)
    removed = {kind: [] for kind, _, _ in _RESOURCE_COMMANDS}
    errors: list[str] = []
    found = False
    for attempt in range(1, max(1, attempts) + 1):
        resources, query_errors = _project_resources(project_name)
        errors.extend(query_errors)
        found = found or any(resources.values())
        if not query_errors and not any(resources.values()):
            return {
                "status": "cleaned" if found else "already_clean",
                "verified": True,
                "project_name": project_name,
                "attempts": attempt,
                "removed": removed,
                "images_retained": True,
                "errors": errors,
            }
        for kind, _, remove_args in _RESOURCE_COMMANDS:
            identifiers = resources[kind]
            if not identifiers:
                continue
            try:
                result = _docker([*remove_args, *identifiers], timeout=60)
            except (OSError, subprocess.TimeoutExpired) as error:
                errors.append(f"{kind}: {error}")
                continue
            if result.returncode:
                errors.append(f"{kind}: {result.stderr.strip() or result.stdout.strip() or 'docker removal failed'}")
            else:
                removed[kind].extend(identifiers)
        if attempt < attempts:
            time.sleep(0.25 * attempt)

    remaining, query_errors = _project_resources(project_name)
    errors.extend(query_errors)
    return {
        "status": "cleanup_failed",
        "verified": False,
        "project_name": project_name,
        "attempts": max(1, attempts),
        "removed": removed,
        "remaining": remaining,
        "images_retained": True,
        "errors": errors,
    }


def reap_output_root(output_root: Path) -> list[dict[str, Any]]:
    """Clean stale trials discoverable from one configured Eval output root."""
    if not output_root.is_dir():
        return []
    reports: list[dict[str, Any]] = []
    for request_path in sorted(output_root.glob("harbor-*/request.json")):
        try:
            request = json.loads(request_path.read_text(encoding="utf-8"))
            trial_name = str(request["trial_name"])
            compose_project_name(trial_name)
        except (OSError, KeyError, TypeError, ValueError, json.JSONDecodeError):
            continue
        report = cleanup_trial_environment(trial_name)
        if report["status"] != "already_clean":
            reports.append(report)
    return reports


def inspect_image(reference: str | None) -> dict[str, Any] | None:
    """Record the concrete cached image used by Docker without pulling it."""
    if not reference:
        return None
    try:
        result = _docker(["image", "inspect", reference], timeout=15)
    except (OSError, subprocess.TimeoutExpired):
        return {"reference": reference, "available": False}
    if result.returncode:
        return {"reference": reference, "available": False}
    try:
        item = json.loads(result.stdout)[0]
    except (IndexError, KeyError, TypeError, json.JSONDecodeError):
        return {"reference": reference, "available": False}
    return {
        "reference": reference,
        "available": True,
        "image_id": item.get("Id"),
        "repo_digests": sorted(item.get("RepoDigests") or []),
    }
